#!/usr/bin/env node
'use strict';

/**
 * SessionStart hook: keeps a stable path <claude config dir>/vampirecoder-statusline
 * pointing at this plugin's install folder. The plugin folder changes with every version,
 * but settings.json's statusLine command can only hold one fixed path, so it uses this path.
 *
 * Link strategy (first that works):
 *   1. POSIX: symlink. Windows: directory junction (needs no admin / Developer Mode).
 *   2. Fallback: a real folder holding a tiny forwarding script (works on any filesystem).
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ENTRY = 'vampirecoder-claudecode-statusline.cjs';
const IS_WIN = process.platform === 'win32';

/** Normalize a path for comparison (Windows junctions return \\?\ prefixes / trailing slashes). */
function norm(p) {
  let s = String(p).replace(/^\\\\\?\\/, '');
  s = path.resolve(s).replace(/[\\/]+$/, '');
  return IS_WIN ? s.toLowerCase() : s;
}

function removeAny(target) {
  try { fs.rmSync(target, { recursive: true, force: true }); } catch {}
}

function writeForwarder(dir, root) {
  fs.mkdirSync(dir, { recursive: true });
  const target = path.join(root, ENTRY);
  fs.writeFileSync(
    path.join(dir, ENTRY),
    `'use strict';\n// Auto-generated by link-statusline.cjs; forwards to the current plugin version.\nrequire(${JSON.stringify(target)});\n`
  );
  fs.writeFileSync(path.join(dir, '.plugin-root'), root);
}

try {
  const root = process.env.CLAUDE_PLUGIN_ROOT || path.resolve(__dirname, '..');
  const link = path.join(process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude'), 'vampirecoder-statusline');

  let st = null;
  try { st = fs.lstatSync(link); } catch {}

  let upToDate = false;
  if (st && st.isSymbolicLink()) {
    try { upToDate = norm(fs.readlinkSync(link)) === norm(root); } catch {}
  } else if (st && st.isDirectory()) {
    // Forwarder folder: current if it records this root.
    try { upToDate = fs.readFileSync(path.join(link, '.plugin-root'), 'utf8') === root; } catch {}
  }

  if (!upToDate) {
    removeAny(link);
    try {
      fs.mkdirSync(path.dirname(link), { recursive: true });
      fs.symlinkSync(root, link, IS_WIN ? 'junction' : 'dir');
    } catch {
      removeAny(link);
      writeForwarder(link, root);
    }
  }
} catch {}
console.log(JSON.stringify({ continue: true }));
